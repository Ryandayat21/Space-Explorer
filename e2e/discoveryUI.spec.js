import { test, expect } from './fixtures.js';
test('discovery combobox keyboard, empty state, grouped list and information hierarchy', async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/'); await expect(page.locator('#loading-screen')).toHaveClass(/done/);
  await page.locator('#mode-toggle').click(); await expect.poll(() => page.evaluate(() => window.__observer.mode().transitioning)).toBe(false);
  await page.keyboard.press('/'); const input = page.getByRole('combobox'); await expect(input).toBeFocused();
  const list = page.locator('#search-results'); await expect(list).toBeVisible(); await expect(list.getByRole('option')).toHaveCount(13);
  await input.fill('Sirius'); await expect(list.locator('mark')).toHaveText('Sirius');
  await input.press('ArrowDown'); await expect(input).toHaveAttribute('aria-activedescendant', 'search-option-0');
  await expect(list.getByRole('option')).toHaveAttribute('aria-selected', 'true'); await input.press('Enter');
  const panel = page.locator('#galaxy-landmark-panel'); await expect(panel).toBeVisible();
  await expect(panel.getByRole('heading', { name: 'Sirius', exact: true })).toBeVisible();
  for (const title of ['Overview', 'Location', 'Scientific Data', 'Accuracy Notice', 'Sources']) await expect(panel.getByRole('heading', { name: title, exact: true })).toHaveCount(1);
  await expect(panel.locator('dd')).toContainText(['Wilayah lokal', '8,6', 'Star System', '7,2', '0', '1']);
  const selected = page.locator('[data-landmark="sirius"]'); await expect(selected).toHaveAttribute('aria-pressed', 'true');
  await page.locator('.galaxy-landmark-list > summary').click(); await expect(selected).toBeVisible();
  const left = await page.locator('#galaxy-placeholder').boundingBox(); expect(left.y + left.height).toBeLessThan(page.viewportSize().height - 70);
  await page.screenshot({ path: testInfo.outputPath('discovery-desktop.png') });
  await expect(page.locator('.landmark-category')).toHaveCount(5);
  await selected.focus(); await page.keyboard.press('Enter'); await expect(panel).toBeVisible();
  await panel.getByRole('button', { name: 'Fokus ke landmark' }).click(); await expect(panel).toBeVisible();
  await page.keyboard.press('Escape'); await expect(panel).toBeHidden();
  await input.fill('xxxx-no-result'); await expect(list).toContainText('Objek tidak ditemukan. Coba nama atau kategori lain.');
  await input.press('ArrowDown'); await expect(input).not.toHaveAttribute('aria-activedescendant');
  await page.getByRole('button', { name: 'Hapus pencarian' }).click(); await expect(input).toHaveValue(''); await expect(list).toContainText('Terakhir dipilih');
  const popup = await list.boundingBox(); expect(popup.x).toBeGreaterThanOrEqual(left.x + left.width);
  await page.screenshot({ path: testInfo.outputPath('discovery-search.png') });
  await input.press('ArrowDown'); await input.press('ArrowDown'); await input.press('ArrowUp'); await expect(list.locator('[aria-selected=true]')).toHaveCount(1);
  await input.press('Tab'); await expect(list).toBeHidden();
  await input.fill('earth'); await input.press('Enter'); await expect(page.locator('#object-name')).toHaveText('Bumi');
  await expect.poll(() => page.evaluate(() => window.__observer.mode().id)).toBe('solar-system');
});
test('compact discovery panel stays below search and keyboard close works', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' }); await page.goto('/'); await expect(page.locator('#loading-screen')).toHaveClass(/done/);
  const input = page.getByRole('combobox'); await input.fill('Sirius'); await input.press('Enter');
  const panel = page.locator('#galaxy-landmark-panel'); await expect(panel).toBeVisible();
  await page.setViewportSize({ width: 820, height: 768 });
  await expect.poll(async () => (await panel.boundingBox()).height).toBeLessThan(768 * .43); expect((await panel.boundingBox()).y).toBeGreaterThan(300);
  await page.setViewportSize({ width: 390, height: 844 }); await expect(input).toBeVisible();
  await page.getByRole('button', { name: 'Tutup panel informasi', exact: true }).click(); await expect(panel).toBeHidden();
  await input.fill('M42'); await input.press('Enter'); await expect(panel.locator('h2')).toHaveText('Orion Nebula');
  await page.keyboard.press('Escape'); await expect(panel).toBeHidden();
});
